#!/usr/bin/env node
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, join, relative } from 'node:path';

const SRC_DIR = resolve('src');
const OWNER_TODO_FILE = resolve('OWNER_TODO.md');
const isStrict = process.argv.includes('--strict') || process.env.STRICT_CHECK === 'true';

const EXTENSIONS = new Set(['.astro', '.ts', '.js', '.md', '.mdx', '.json', '.html']);

/**
 * @param {string} dir
 * @returns {Promise<string[]>}
 */
async function getFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const res = join(dir, entry.name);
      return entry.isDirectory() ? getFiles(res) : res;
    })
  );
  return files.flat();
}

/**
 * Scans files for [[CONFIRM: ...]] and <PlaceholderChip ...>
 */
async function scanPlaceholders() {
  const allFiles = await getFiles(SRC_DIR);
  const targetFiles = allFiles.filter((f) => EXTENSIONS.has(f.slice(f.lastIndexOf('.'))));

  const findings = [];

  for (const file of targetFiles) {
    const content = await readFile(file, 'utf-8');
    const lines = content.split('\n');

    lines.forEach((lineText, idx) => {
      const lineNum = idx + 1;

      // Match [[CONFIRM: ...]]
      const patternRegex = /\[\[CONFIRM(?::\s*([^\]]+))?\]\]/g;
      let match;
      while ((match = patternRegex.exec(lineText)) !== null) {
        findings.push({
          file: relative(process.cwd(), file),
          line: lineNum,
          type: 'pattern',
          detail: match[1] ? match[1].trim() : 'Unspecified confirmation needed',
          raw: match[0],
        });
      }

      // Match <PlaceholderChip needed="..."
      const chipRegex = /<PlaceholderChip[^>]*needed="([^"]+)"/g;
      let chipMatch;
      while ((chipMatch = chipRegex.exec(lineText)) !== null) {
        // avoid duplicating if the line also has [[CONFIRM]]
        if (!lineText.includes('[[CONFIRM')) {
          findings.push({
            file: relative(process.cwd(), file),
            line: lineNum,
            type: 'chip',
            detail: chipMatch[1].trim(),
            raw: chipMatch[0],
          });
        }
      }
    });
  }

  return findings;
}

async function updateOwnerTodo(findings) {
  let existingContent = '';
  try {
    existingContent = await readFile(OWNER_TODO_FILE, 'utf-8');
  } catch {
    // create new
  }

  const timestamp = new Date().toISOString();
  let markdown = `# OWNER_TODO.md — Launch Verification Checklist\n\n`;
  markdown += `> Auto-generated by \`npm run check:placeholders\` on ${timestamp}.\n`;
  markdown += `> **Rule 2 & Section 12:** Zero invented facts. All items below must be verified by the business owner before production launch.\n\n`;

  markdown += `## Active Codebase Placeholders (${findings.length} found)\n\n`;

  if (findings.length === 0) {
    markdown += `✅ **Zero placeholders remaining in codebase! The site is ready for final production build.**\n\n`;
  } else {
    markdown += `| File | Line | Required Fact / Action |\n`;
    markdown += `|---|---|---|\n`;
    for (const f of findings) {
      markdown += `| \`${f.file}\` | L${f.line} | ${f.detail} |\n`;
    }
    markdown += `\n`;
  }

  markdown += `## 10 Core Facts Needed from Owner (Section 17)\n\n`;
  markdown += `1. **Legal business name, year started, GSTIN / Udyam number (if any)**\n`;
  markdown += `   - Status: Pending verification\n`;
  markdown += `2. **Real working address and city. Which region do we serve?**\n`;
  markdown += `   - Status: Current placeholder city/address pending owner confirmation\n`;
  markdown += `3. **Real counts of websites and projects delivered (with proof)**\n`;
  markdown += `   - Status: Avoided conflicting claims (500+ vs 50 vs 23) pending actual verified count\n`;
  markdown += `4. **Testimonials: full name, business, link, permission**\n`;
  markdown += `   - Status: Section hidden if fewer than 2 verified testimonials with permission exist\n`;
  markdown += `5. **Team: names, roles, photos, LinkedIn**\n`;
  markdown += `   - Status: Single-founder mode active with founder name pending confirmation\n`;
  markdown += `6. **Which services can be delivered today. Tamil support: yes or no**\n`;
  markdown += `   - Status: Flagship WhatsApp agent marked ready; Tamil voice agent postponed\n`;
  markdown += `7. **Final prices, payment terms, support terms, response time**\n`;
  markdown += `   - Status: Suggested market ranges noted as 'from ₹X'; awaiting owner confirmation\n`;
  markdown += `8. **Booking link, WhatsApp number, social links**\n`;
  markdown += `   - Status: Cal.com URL and WhatsApp phone number placeholders active\n`;
  markdown += `9. **Status of PO Sentry (prototype or pilot) and any pilot clients who agree to be named**\n`;
  markdown += `   - Status: Honestly marked as 'prototype'\n`;
  markdown += `10. **Any work that must not be shown (employer or NDA)**\n`;
  markdown += `    - Status: Strict filter applied\n`;

  await writeFile(OWNER_TODO_FILE, markdown, 'utf-8');
}

async function main() {
  console.log('🔍 Scanning src/ for placeholders and unconfirmed facts...');
  const findings = await scanPlaceholders();

  await updateOwnerTodo(findings);

  if (findings.length > 0) {
    console.log(`\n⚠️  Found ${findings.length} placeholder(s) across codebase:`);
    for (const f of findings) {
      console.log(`   - ${f.file}:${f.line} -> ${f.detail}`);
    }
    console.log(`\n📋 Updated ${OWNER_TODO_FILE}`);

    if (isStrict) {
      console.error('\n❌ STRICT CHECK FAILED: Cannot build for production with remaining [[CONFIRM]] placeholders.');
      process.exit(1);
    }
  } else {
    console.log('\n✅ No placeholders found. Codebase verified against fake facts!');
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
